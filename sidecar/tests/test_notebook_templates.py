def test_record_version_refuses_to_change_a_released_version(tmp_path, monkeypatch):
    import shutil
    folder = tmp_path / "notebook_templates"
    shutil.copytree(nt.HERE, folder, ignore=shutil.ignore_patterns("__pycache__", "*.py"))
    monkeypatch.setattr(nt, "HERE", folder)
    assert nt.record_version() == {k: v[nt.VERSION] for k, v in json.loads((folder / "standards.json").read_text()).items()}
    path = folder / "fabric" / "silver.ipynb"
    nb = json.loads(path.read_text())
    _cell(nb, "standard", "step-2")["source"].append("\nx = 1")
    path.write_text(json.dumps(nb))
    with pytest.raises(ValueError, match="raise VERSION"):
        nt.record_version()
