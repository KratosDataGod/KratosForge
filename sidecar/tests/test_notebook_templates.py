ALL = [(t["platform"], t["kind"]) for t in nt.catalog()]


def _code(nb):
    return [c for c in nb["cells"] if c["cell_type"] == "code"]


def _cell(nb, role, cell=""):
    for c in _code(nb):
        m = nt.marker(nt.source_of(c))
        if m and m["role"] == role and (not cell or m["cell"] == cell):
            return c
    raise AssertionError(f"no {role} cell {cell}")


def test_catalog_covers_every_platform_and_kind():
    assert len(ALL) == len(nt.PLATFORMS) * len(nt.KINDS) == 12
    assert set(nt.SKIN_PLATFORM.values()) <= set(nt.PLATFORMS)
    with pytest.raises(ValueError):
        nt.path("oracle", "silver")
    with pytest.raises(ValueError):
        nt.path("fabric", "bronze")


@pytest.mark.parametrize("platform,kind", ALL)
def test_template_is_a_notebook_with_its_markup(platform, kind):
    nb = nt.load(platform, kind)
    assert nb["nbformat"] == 4
    meta = nb["metadata"]["kratosforge"]
    assert meta["template"] == {"id": nt.KINDS[kind][0], "version": nt.VERSION, "platform": platform, "kind": kind}
    assert meta["support"]["tier"] == "enterprise-template"
    first = "".join(nb["cells"][0]["source"])
    assert nb["cells"][0]["cell_type"] == "markdown" and "Standards this notebook follows" in first
    assert "Who supports this notebook" in first
    params = [c for c in _code(nb) if "parameters" in c["metadata"].get("tags", [])]
    assert len(params) == 1 and nt.marker(nt.source_of(params[0]))["role"] == "parameters"
    for c in _code(nb):  # every code cell is marked, so nothing in a template is unowned
        m = nt.marker(nt.source_of(c))
        assert m and m["template"] == meta["template"]["id"] and m["platform"] == platform
        assert m["version"] == nt.VERSION
        compile(nt.source_of(c), f"{platform}/{kind}", "exec")


@pytest.mark.parametrize("platform,kind", ALL)
def test_template_conforms_and_matches_its_released_hashes(platform, kind):
    nb = nt.load(platform, kind)
    result = nt.check(nb)
    assert result["status"] == "conforms", result["changes"]
    assert not result["upgrade_available"]
    released = json.loads((nt.HERE / "standards.json").read_text())[f"{platform}/{kind}"][nt.VERSION]
    marked = {nt.marker(nt.source_of(c))["cell"]: nt.cell_hash(nt.source_of(c))
              for c in _code(nb) if nt.marker(nt.source_of(c))["role"] == "standard"}
    assert marked == released


@pytest.mark.parametrize("platform,kind", ALL)
def test_template_follows_the_notebook_rules(platform, kind):
    found = notebook_practices.check([nt.source_of(c) for c in _code(nt.load(platform, kind))], scheduled=True)
    serious = [f for f in found["findings"] if f["severity"] in ("Error", "Warning")]
    if platform == "snowflake":
        # Snowpark runs SQL with collect(); each statement returns one summary row or at most five rows.
        serious = [f for f in serious if f["rule_id"] != "NB003"]
    assert serious == []
    assert not [f for f in found["findings"] if f["rule_id"] == "NB006"]  # no SELECT *


@pytest.mark.parametrize("platform,kind", ALL)
def test_template_has_no_secrets_ids_or_overwrites(platform, kind):
    text = "\n".join(nt.source_of(c) for c in _code(nt.load(platform, kind)))
    assert not re.search(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", text)
    assert 'mode("overwrite")' not in text and "INSERT OVERWRITE" not in text.upper()
    assert "MERGE INTO" in text


def test_silver_keys_fit_each_platform():
    fabric = "\n".join(nt.source_of(c) for c in _code(nt.load("fabric", "silver")))
    databricks = "\n".join(nt.source_of(c) for c in _code(nt.load("databricks", "silver")))
    snowflake = json.dumps(nt.load("snowflake", "silver"))
    assert "ROW_NUMBER() OVER (ORDER BY n.bk) AS INT" in fabric and "concurrent" in fabric
    assert "GENERATED BY DEFAULT AS IDENTITY" in json.dumps(nt.load("databricks", "silver"))
    assert "INSERT ({c(bk_column)}, create_date)" in databricks  # the identity column issues the key
    assert "_SEQ.NEXTVAL" in snowflake and "INSERT ({bk_column}, CREATE_DATE)" in snowflake


def _rules_namespace(platform, **params):
    """The fact rules cell, run with stand-ins for what the setup cell defines."""
    nb = nt.load(platform, "gold_fact")
    ns: dict = {}
    exec(nt.source_of(_cell(nb, "parameters")), ns)  # noqa: S102 - the template's own literal values
    ns.update(params)
    ns.update(re=re, table_exists=lambda name: False,
              q=lambda name: name, c=lambda name: name, checked_type=lambda t: t)
    exec(nt.source_of(_cell(nb, "standard", "step-1")), ns)  # noqa: S102
    return ns


@pytest.mark.parametrize("platform", list(nt.PLATFORMS))
@pytest.mark.parametrize("change,message", [
    ({"measures": {"order_id": "int"}}, "degenerate field"),
    ({"measures": {"order_status": "int"}}, "degenerate field"),
    ({"measures": {"status": "string"}}, "a fact holds numbers"),
    ({"grain_columns": ["order_id"]}, "must be a dimension key"),
    ({"grain": " "}, "Declare the grain"),
])
def test_fact_rules_refuse_degenerate_and_descriptive_fields(platform, change, message):
    _rules_namespace(platform)  # the template's own parameters pass
    with pytest.raises(ValueError, match=message):
        _rules_namespace(platform, **change)


@pytest.mark.parametrize("platform", list(nt.PLATFORMS))
def test_fact_rules_refuse_a_key_not_named_sk(platform):
    dims = [{"fk": "customer_key", "dim": "d", "dim_sk": "s", "dim_key": "k", "source": "x"}]
    with pytest.raises(ValueError, match="name dimension keys"):
        _rules_namespace(platform, dimensions=dims, grain_columns=["customer_key"])


# ---- conformance


def test_editing_a_standard_cell_makes_it_domain_owned():
    nb = nt.load("fabric", "silver")
    _cell(nb, "standard", "step-4")["source"].append("\nprint('mine')")
    result = nt.check(nb)
    assert result["status"] == "domain-owned"
    assert result["changes"] == ["Cell 11, the standard cell step-4, was edited"]


def test_whitespace_and_line_endings_dont_count_as_edits():
    nb = nt.load("fabric", "silver")
    cell = _cell(nb, "standard", "step-1")
    cell["source"] = [line.replace("\n", "  \r\n") for line in cell["source"]]
    assert nt.check(nb)["status"] == "conforms"


def test_added_code_and_code_in_parameters_make_it_domain_owned():
    nb = nt.load("databricks", "gold_fact")
    nb["cells"].append({"cell_type": "code", "metadata": {}, "outputs": [], "execution_count": None,
                        "source": ["spark.sql('DELETE FROM x')"]})
    _cell(nb, "parameters")["source"].append("\nimport os\n")
    changes = nt.check(nb)["changes"]
    assert any("code the template doesn't have" in c for c in changes)
    assert any("Parameters cell has code" in c for c in changes)


def test_markdown_notes_and_parameter_values_keep_it_conforming():
    nb = nt.load("snowflake", "gold_dim_type2")
    nb["cells"].insert(2, {"cell_type": "markdown", "metadata": {}, "source": ["Owned by the Sales domain."]})
    params = _cell(nb, "parameters")
    params["source"] = [line.replace("GOLD.SALES.DIM_CUSTOMER", "GOLD.SALES.DIM_STORE") for line in params["source"]]
    result = nt.check(nb)
    assert result["status"] == "conforms"
    assert result["parameters"]["target_table"] == "GOLD.SALES.DIM_STORE"


def test_reordered_cells_make_it_domain_owned():
    nb = nt.load("fabric", "silver")
    cells = nb["cells"]
    i, j = cells.index(_cell(nb, "standard", "step-5")), cells.index(_cell(nb, "standard", "step-6"))
    cells[i], cells[j] = cells[j], cells[i]  # the result check would run before the MERGE
    assert nt.check(nb)["changes"] == [f"Cell {j + 1}, the standard cell step-5, is out of order"]
    nb = nt.load("fabric", "silver")
    params = _cell(nb, "parameters")
    nb["cells"].remove(params)
    nb["cells"].append(params)
    assert nt.check(nb)["changes"] == [f"Cell {len(nb['cells'])}, the Parameters cell, is out of order: "
                                       "it must come before the standard cells"]


def test_removed_cell_and_missing_parameter_are_named():
    nb = nt.load("fabric", "gold_dim_type1")
    nb["cells"] = [c for c in nb["cells"] if nt.marker(nt.source_of(c)) is None
                   or nt.marker(nt.source_of(c))["cell"] != "step-3"]
    params = _cell(nb, "parameters")
    params["source"] = [line for line in params["source"] if not line.startswith("run_id")]
    changes = nt.check(nb)["changes"]
    assert "The standard cell step-3 was removed" in changes
    assert "The Parameters cell is missing run_id" in changes


