"""Which of Spark's JSON, CSV and Parquet read options this PC's ``spark.read`` takes (WR-301, #1669).

``spark_read_options.json`` lists Spark 3.5's read options for each format (where they come from is in
the file). Each one is put to ``spark_local.read_option_refusal``, the check the reader itself runs, so
the page says what a notebook gets: the option is honoured, or the read stops and says why. Nothing is
dropped quietly. ``python -m fabric_desktop.spark_read_options`` in sidecar/ writes
docs/spark-read-options.md, and CI fails when the page is stale.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .spark_local import read_option_refusal

DATA = Path(__file__).with_name("spark_read_options.json")
DOC = Path(__file__).resolve().parents[2] / "docs" / "spark-read-options.md"
FORMATS = ("json", "csv", "parquet")
_LABELS = {"json": "JSON", "csv": "CSV", "parquet": "Parquet"}

# What an honoured option takes on this PC when that is less than Spark takes, by format and lower-case name.
_LIMITS = {
    ("json", "mode"): "PERMISSIVE (a malformed line is a row of nulls) or FAILFAST; not DROPMALFORMED, and not "
                      "PERMISSIVE with multiLine",
    ("json", "encoding"): "UTF-8 only",
    ("csv", "encoding"): "UTF-8 only",
    ("csv", "mode"): "PERMISSIVE, or DROPMALFORMED and FAILFAST with read.schema()",
    ("parquet", "datetimerebasemode"): "CORRECTED only: dates and times are read as written",
    ("parquet", "int96rebasemode"): "CORRECTED only: dates and times are read as written",
}


def load() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(DATA.read_text(encoding="utf-8"))
    return data


def rows() -> list[dict[str, str]]:
    """Every option of every format: ``{format, name, status, note}``, status ``honoured`` or ``refused``."""
    data = load()
    out = []
    for fmt in FORMATS:
        for name in data[fmt]:
            refused = read_option_refusal(fmt, [(name, None)], has_schema=False)
            if refused:
                # the usual reason ("doesn't take the option") is the status itself; say any other
                note = "" if refused.startswith("doesn't take") else f"This PC's Spark {refused}."
                out.append({"format": fmt, "name": name, "status": "refused", "note": note})
            else:
                out.append({"format": fmt, "name": name, "status": "honoured",
                            "note": _LIMITS.get((fmt, name.lower()), "")})
    return out


def markdown(found: list[dict[str, str]]) -> str:
    data = load()
    lines = [
        "# Spark read options on this PC",
        "",
        "<!-- Generated by sidecar/fabric_desktop/spark_read_options.py. Don't edit by hand: run",
        "     `python -m fabric_desktop.spark_read_options` in sidecar/ and commit the result. -->",
        "",
        f"Every read option Spark {data['spark']} documents for `spark.read.json`, `spark.read.csv` and",
        "`spark.read.parquet`, with what a notebook's `spark.read` does with it on this PC:",
        "",
        "- **Honoured**: read as Spark reads it, within the limit noted.",
        "- **Refused**: the read stops before it starts and says which option, so a file is never read",
        "  with an option quietly left out. Run the cell in Fabric, or read without the option.",
        "",
        "Each status comes from the check the reader itself runs, and CI regenerates this page, so it",
        "changes when an option is added or refused. Options are matched without regard to case, as in",
        "Spark. Time travel (`versionAsOf`, `timestampAsOf`) is taken by every reader.",
        "",
        "| Format | Honoured | Refused |",
        "| --- | ---: | ---: |",
    ]
    for fmt in FORMATS:
        mine = [r for r in found if r["format"] == fmt]
        lines.append(f"| {_LABELS[fmt]} | {sum(r['status'] == 'honoured' for r in mine)} | "
                     f"{sum(r['status'] == 'refused' for r in mine)} |")
    lines.append("")
    for fmt in FORMATS:
        aliases = data["aliases"].get(fmt, {})
        lines += [f"## {_LABELS[fmt]}", ""]
        if aliases:
            lines += ["Also taken under another name: " + ", ".join(
                f"`{a}` (as `{b}`)" for a, b in sorted(aliases.items())) + ".", ""]
        lines += ["| Option | Status | Note |", "| --- | --- | --- |"]
        for r in (r for r in found if r["format"] == fmt):
            lines.append(f"| `{r['name']}` | {r['status'].capitalize()} | {r['note'].replace('|', '/')} |")
        lines.append("")
    lines += ["Source: " + data["source"], ""]
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover - writes the docs page
    from .jsonfile import write_text
    write_text(DOC, markdown(rows()), newline="\n")  # LF, like the committed page
    print(f"Wrote {DOC}")
