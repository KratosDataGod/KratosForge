"""Mutation batch 42: the Spark read options page (spark_read_options.py).

The module's own tests check the committed docs page against ``markdown(rows())``; that test reads
docs/, so the mutation runs leave it out and these pin the page's parts directly, from a small
stand-in options file, without reading docs/.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from fabric_desktop import spark_read_options as sro

DATA = {
    "spark": "9.9.9",
    "source": "a stand-in list",
    "aliases": {"csv": {"delimiter": "sep", "charset": "encoding"}},
    "json": ["multiLine", "allowComments"],
    "csv": ["sep", "nanValue", "mode"],
    "parquet": [],
}


@pytest.fixture
def data(monkeypatch):
    monkeypatch.setattr(sro, "load", lambda: DATA)
    return DATA


def test_the_page_is_written_beside_the_repo_docs():
    root = Path(sro.__file__).resolve().parents[2]
    assert sro.DOC == root / "docs" / "spark-read-options.md"
    assert (root / "sidecar" / "fabric_desktop" / "spark_read_options.py").is_file()


def test_rows_say_honoured_or_refused_for_each_option_in_format_order(data):
    rows = sro.rows()
    assert [(r["format"], r["name"], r["status"]) for r in rows] == [
        ("json", "multiLine", "honoured"), ("json", "allowComments", "refused"),
        ("csv", "sep", "honoured"), ("csv", "nanValue", "refused"), ("csv", "mode", "honoured"),
    ]


def test_the_usual_refusal_has_no_note_and_a_limit_is_noted_by_lower_case_name(data):
    by = {(r["format"], r["name"]): r["note"] for r in sro.rows()}
    assert by[("json", "allowComments")] == ""  # "doesn't take ..." is the status itself
    assert by[("json", "multiLine")] == ""  # honoured with no limit
    assert by[("csv", "mode")] == sro._LIMITS[("csv", "mode")]  # "mode" matched as lower case


def test_any_other_refusal_reason_is_the_note(data, monkeypatch):
    def refusal(fmt, options, has_schema=False):
        name = options[0][0]
        return "reads CSV files as UTF-8 only" if name == "nanValue" else None
    monkeypatch.setattr(sro, "read_option_refusal", refusal)
    by = {r["name"]: r for r in sro.rows()}
    assert by["nanValue"]["status"] == "refused"
    assert by["nanValue"]["note"] == "This PC's Spark reads CSV files as UTF-8 only."


def _found():
    return [
        {"format": "json", "name": "multiLine", "status": "honoured", "note": ""},
        {"format": "json", "name": "allowComments", "status": "refused", "note": ""},
        {"format": "csv", "name": "sep", "status": "honoured", "note": "a | b"},
        {"format": "csv", "name": "nanValue", "status": "refused", "note": ""},
        {"format": "csv", "name": "mode", "status": "refused", "note": ""},
    ]


def test_the_page_counts_honoured_and_refused_per_format(data):
    page = sro.markdown(_found())
    assert "| JSON | 1 | 1 |" in page
    assert "| CSV | 1 | 2 |" in page
    assert "| Parquet | 0 | 0 |" in page
    assert "Every read option Spark 9.9.9 documents" in page
    assert page.endswith("Source: a stand-in list\n")


def test_each_format_lists_its_own_options_with_status_and_note(data):
    lines = sro.markdown(_found()).splitlines()
    json_at, csv_at, pq_at = lines.index("## JSON"), lines.index("## CSV"), lines.index("## Parquet")
    assert json_at < csv_at < pq_at
    json_part, csv_part, pq_part = lines[json_at:csv_at], lines[csv_at:pq_at], lines[pq_at:]
    assert "| `multiLine` | Honoured |  |" in json_part
    assert "| `allowComments` | Refused |  |" in json_part
    assert not any("`sep`" in x for x in json_part)
    assert "| `sep` | Honoured | a / b |" in csv_part  # a | in a note can't break the table
    assert "| `nanValue` | Refused |  |" in csv_part
    assert not any(x.startswith("| `") for x in pq_part)


def test_aliases_are_listed_sorted_only_for_formats_that_have_them(data):
    lines = sro.markdown(_found()).splitlines()
    csv_at = lines.index("## CSV")
    assert lines[csv_at + 2] == "Also taken under another name: `charset` (as `encoding`), `delimiter` (as `sep`)."
    assert lines[csv_at + 3] == ""
    assert not any(x.startswith("Also taken") for x in lines[lines.index("## JSON"):csv_at])


def test_the_page_is_lines_joined_with_newlines(data):
    page = sro.markdown(_found())
    assert page.startswith("# Spark read options on this PC\n\n<!-- Generated by")
    assert "\r" not in page and "\n\n## JSON\n\n" in page
