"""Databricks SQL's table statements in a DuckDB engine cell (WR-309): each answers as Databricks documents
(docs.databricks.com: CREATE TABLE [USING], generated and identity columns, constraints, MERGE INTO,
TBLPROPERTIES), or is refused by name so nothing runs with another answer."""

from __future__ import annotations

import re

import pytest

from fabric_desktop.engines import local_sql
from fabric_desktop.engines.contract import CellRequest, SessionConfig


@pytest.fixture()
def cell():
    session = local_sql.DuckDBSession(SessionConfig("nb"))

    def run(code):
        result = session.execute(CellRequest(code, "sql", "databricks"))
        output = result.outputs[-1] if result.outputs else {}
        if result.status != "ok":
            return "error: " + str(output.get("evalue") or output.get("text"))
        return output.get("rows")
    yield run
    session.close()


def _refused(answer, what):
    assert answer.startswith(f"error: {what} can't run on this PC the way it runs in Databricks, because "), answer
    assert ", so nothing ran. " in answer
    assert "Run the cell on a Databricks SQL warehouse, or " in answer


def test_using_delta_is_the_default_so_it_makes_the_table(cell):
    assert cell("CREATE TABLE sales USING DELTA AS SELECT * FROM (VALUES (1, 'a', 10), (2, 'a', 20), (3, 'b', 30)) "
                "t(id, g, v)") == [[3]]
    assert cell("CREATE TABLE more (a INT) USING delta") == []
    assert cell("SELECT count(*) FROM sales") == [[3]]
    _refused(cell("CREATE TABLE pq (a INT) USING PARQUET"), "USING PARQUET")


def test_qualify_and_pivot_answer_as_databricks(cell):
    cell("CREATE TABLE sales AS SELECT * FROM (VALUES (1, 'a', 10), (2, 'a', 20), (3, 'b', 30)) t(id, g, v)")
    assert cell("SELECT id FROM sales QUALIFY ROW_NUMBER() OVER (PARTITION BY g ORDER BY v DESC) = 1 "
                "ORDER BY id") == [[2], [3]]
    assert cell("SELECT * FROM (SELECT g, v FROM sales) PIVOT (MAX(v) AS m, COUNT(v) AS c FOR g IN ('a' AS x, 'b' AS y))"
                ) == [[20, 2, 30, 1]]


def test_identity_columns_number_rows_from_start_by_step(cell):
    assert cell("CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, name STRING) USING DELTA") == []
    cell("INSERT INTO ids (name) VALUES ('x'), ('y')")
    cell("INSERT INTO ids BY NAME SELECT 'z' AS name")
    assert cell("SELECT id, name FROM ids ORDER BY id") == [[1, "x"], [2, "y"], [3, "z"]]
    cell("CREATE TABLE down (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY -5), name STRING)")
    cell("INSERT INTO down (name) VALUES ('a'), ('b')")
    cell("INSERT INTO down VALUES (100, 'c')")  # BY DEFAULT takes a value a write gives
    assert cell("SELECT id, name FROM down ORDER BY name") == [[10, "a"], [5, "b"], [100, "c"]]


@pytest.mark.parametrize("write", [
    "INSERT INTO ids (id, name) VALUES (5, 'z')",
    "INSERT INTO ids VALUES (5, 'z')",
    "INSERT INTO ids BY NAME SELECT 5 AS id, 'z' AS name",
    "UPDATE ids SET id = 3",
    "MERGE INTO ids t USING (SELECT 1 AS id, 'w' AS name) s ON t.name = s.name WHEN NOT MATCHED THEN INSERT *",
    "MERGE INTO ids t USING (SELECT 'x' AS name) s ON t.name = s.name WHEN MATCHED THEN UPDATE SET id = 9",
])
def test_a_value_for_a_generated_always_identity_column_is_refused(cell, write):
    cell("CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, name STRING); INSERT INTO ids (name) VALUES ('x')")
    _refused(cell(write), "A write that gives id a value")
    assert cell("SELECT id, name FROM ids") == [[1, "x"]]


def test_the_identity_check_sees_a_table_the_same_cell_makes(cell):
    _refused(cell("CREATE TABLE c (Id BIGINT GENERATED ALWAYS AS IDENTITY, n STRING); INSERT INTO c VALUES (1, 'a')"),
             "A write that gives id a value")
    assert cell("CREATE TABLE c (Id BIGINT GENERATED ALWAYS AS IDENTITY, n STRING); INSERT INTO c (n) VALUES ('a'); "
                "SELECT * FROM c") == [[1, "a"]]


@pytest.mark.parametrize(("ddl", "what"), [
    ("CREATE TABLE bad (id INT GENERATED ALWAYS AS IDENTITY)", "Identity column id"),
    ("CREATE TABLE bad (id BIGINT GENERATED ALWAYS AS IDENTITY (INCREMENT BY 0))", "Identity column id"),
])
def test_identity_columns_databricks_refuses_are_refused(cell, ddl, what):
    _refused(cell(ddl), what)


def test_generated_columns_are_worked_out_on_every_write(cell):
    assert cell("CREATE TABLE gen (a INT, b INT GENERATED ALWAYS AS (a * 2))") == []
    cell("INSERT INTO gen (a) VALUES (1), (2)")
    cell("UPDATE gen SET a = 5 WHERE a = 2")
    assert cell("SELECT a, b FROM gen ORDER BY a") == [[1, 2], [5, 10]]
    # a value written into it stops the write; Databricks takes one only when it equals the expression
    assert cell("INSERT INTO gen (a, b) VALUES (3, 6)").startswith("error: ")
    assert cell("SELECT count(*) FROM gen") == [[2]]


def test_a_check_in_create_table_stops_a_write_that_breaks_it(cell):
    cell("CREATE TABLE c2 (a INT, CONSTRAINT pos CHECK (a > 0))")
    assert "CHECK constraint failed" in cell("INSERT INTO c2 VALUES (-1)")
    assert cell("INSERT INTO c2 VALUES (1)") == [[1]]


@pytest.mark.parametrize(("statement", "what"), [
    ("ALTER TABLE t ADD CONSTRAINT pos CHECK (a > 0)", "ALTER TABLE ... ADD CONSTRAINT"),
    ("ALTER TABLE t DROP CONSTRAINT pos", "ALTER TABLE ... DROP CONSTRAINT"),
    ("CREATE TABLE p (a INT) USING DELTA TBLPROPERTIES ('delta.appendOnly' = 'true')", "TBLPROPERTIES"),
    ("CREATE TABLE p (a INT) TBLPROPERTIES ('delta.enableChangeDataFeed' = 'true')", "TBLPROPERTIES"),
    ("ALTER TABLE t SET TBLPROPERTIES ('delta.appendOnly' = 'true')", "ALTER TABLE ... SET TBLPROPERTIES"),
    ("ALTER TABLE t UNSET TBLPROPERTIES ('delta.appendOnly')", "ALTER TABLE ... UNSET TBLPROPERTIES"),
    (("MERGE WITH SCHEMA EVOLUTION INTO t USING s ON t.a = s.a WHEN MATCHED THEN UPDATE SET * "
      "WHEN NOT MATCHED THEN INSERT *"), "MERGE WITH SCHEMA EVOLUTION"),
])
def test_what_only_a_delta_table_does_is_refused_by_name(cell, statement, what):
    cell("CREATE TABLE t (a INT); INSERT INTO t VALUES (-1); CREATE TABLE s (a INT, extra STRING)")
    _refused(cell(statement), what)
    assert cell("SELECT a FROM t") == [[-1]]


def test_merge_with_an_extra_source_column_stops_as_databricks_reference_says(cell):
    # MERGE INTO's reference: UPDATE SET * and INSERT * need the source's columns to be the target's
    cell("CREATE TABLE t (a INT, v INT); INSERT INTO t VALUES (1, 1); "
         "CREATE TABLE s AS SELECT 1 AS a, 2 AS v, 'x' AS extra")
    assert cell("MERGE INTO t USING s ON t.a = s.a WHEN MATCHED THEN UPDATE SET * WHEN NOT MATCHED THEN INSERT *"
                ).startswith("error: ")
    assert cell("MERGE INTO t USING s ON t.a = s.a WHEN MATCHED THEN UPDATE SET v = s.v") == [[1]]
    assert cell("SELECT a, v FROM t") == [[1, 2]]


def test_a_refusal_sqlglot_makes_names_databricks_not_fabric(cell):
    answer = cell("CREATE TABLE p (a INT) LOCATION 'x'")
    assert answer.startswith("error: ") and "Fabric" not in answer and "Databricks" in answer


def _plan_words(plan):
    """The plan's letters only: DuckDB 1 writes CREATE_TABLE in its boxes, DuckDB 2 writes Create Table."""
    return re.sub(r"[^a-z]", "", plan.lower())


@pytest.mark.parametrize("dialect", ["databricks", "spark", "duckdb", "snowflake"])
def test_a_plan_plans_the_first_statement_and_runs_none(dialect):
    session = local_sql.DuckDBSession(SessionConfig("nb"))
    try:
        assert "projection" in _plan_words(session.plan("SELECT 1; CREATE TABLE made AS SELECT 1 AS a", dialect))
        assert session._con.execute("SELECT count(*) FROM duckdb_tables()").fetchall() == [(0,)]
    finally:
        session.close()


def test_a_plan_of_a_table_with_an_identity_column_makes_no_table():
    session = local_sql.DuckDBSession(SessionConfig("nb"))
    try:
        assert "createtable" in _plan_words(session.plan(
            "CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, n STRING)", "databricks"))
        assert session._con.execute("SELECT count(*) FROM duckdb_tables()").fetchall() == [(0,)]
    finally:
        session.close()


def test_partitioning_and_clustering_make_the_table_and_comments_are_kept(cell):
    assert cell("CREATE TABLE p (a INT COMMENT 'the a', b STRING) USING DELTA PARTITIONED BY (a) COMMENT 'tbl'") == []
    assert cell("CREATE TABLE c USING DELTA CLUSTER BY (a) AS SELECT 1 AS a") == [[1]]
    assert cell("SELECT table_name, comment FROM duckdb_tables() ORDER BY 1") == [["c", None], ["p", "tbl"]]
    assert cell("SELECT column_name, comment FROM duckdb_columns() WHERE table_name = 'p' ORDER BY 1") == [
        ["a", "the a"], ["b", None]]
    _refused(cell("CREATE TABLE q (a INT) PARTITIONED BY (d DATE)"), "PARTITIONED BY with column types")


def test_a_plan_of_an_identity_column_leaves_no_sequence():
    session = local_sql.DuckDBSession(SessionConfig("nb"))
    try:
        session.plan("CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, n STRING)", "databricks")
        assert session._con.execute("SELECT count(*) FROM duckdb_sequences()").fetchall() == [(0,)]
    finally:
        session.close()

@pytest.mark.parametrize(("text", "what"), [
    ("TABLE t DROP CONSTRAINT pos", "ALTER TABLE ... DROP CONSTRAINT"),
    ("TABLE t ADD CONSTRAINT pos CHECK (a > 0)", "ALTER TABLE ... ADD CONSTRAINT"),
    ("TABLE t SET TBLPROPERTIES ('a' = 'b')", "ALTER TABLE ... SET TBLPROPERTIES"),
    ("TABLE t UNSET TBLPROPERTIES ('a')", "ALTER TABLE ... UNSET TBLPROPERTIES"),
])
def test_an_alter_sqlglot_reads_only_as_a_command_is_refused_by_name_too(text, what):
    # some builds of sqlglot give up on these clauses and keep the statement as text
    from sqlglot import exp

    from fabric_desktop import databricks_builtins_sql
    with pytest.raises(ValueError, match=rf"^{re.escape(what)} can't run on this PC"):
        databricks_builtins_sql.table_statements(exp.Command(this="ALTER", expression=text))
    assert databricks_builtins_sql.table_statements(exp.Command(this="ALTER", expression="TABLE t RENAME TO u")) \
        == [exp.Command(this="ALTER", expression="TABLE t RENAME TO u")]


@pytest.mark.parametrize("write", [
    "INSERT INTO gen (a, b) VALUES (3, 6)",
    "INSERT INTO gen BY NAME SELECT 3 AS a, 6 AS b",
    "UPDATE gen SET b = 6",
    "MERGE INTO gen t USING (SELECT 1 AS a) s ON t.a = s.a WHEN MATCHED THEN UPDATE SET b = 2",
])
def test_a_value_for_a_generated_column_is_refused_by_name(cell, write):
    cell("CREATE TABLE gen (a INT, b INT GENERATED ALWAYS AS (a * 2)); INSERT INTO gen (a) VALUES (1)")
    answer = cell(write)
    _refused(answer, "A write that gives b a value")
    assert "GENERATED ALWAYS AS (a * 2)" in answer
    assert cell("SELECT a, b FROM gen") == [[1, 2]]
    # the same cell's own CREATE TABLE is read too
    _refused(cell("CREATE TABLE gen2 (a INT, b INT GENERATED ALWAYS AS (a + 1)); " + write.replace("gen", "gen2")),
             "A write that gives b a value")


def test_the_identity_check_reads_the_table_the_write_names(cell):
    cell("CREATE SCHEMA other; CREATE TABLE other.ids (id BIGINT GENERATED ALWAYS AS IDENTITY, name STRING); "
         "CREATE TABLE ids (id BIGINT, name STRING)")
    assert cell("INSERT INTO ids (id, name) VALUES (5, 'z')") == [[1]]
    _refused(cell("INSERT INTO other.ids (id, name) VALUES (5, 'z')"), "A write that gives id a value")
    assert cell("INSERT INTO other.ids (name) VALUES ('y'); SELECT id, name FROM other.ids") == [[1, "y"]]


def test_dropping_or_replacing_a_table_drops_its_identity_sequence():
    session = local_sql.DuckDBSession(SessionConfig("nb"))

    def run(code):
        assert session.execute(CellRequest(code, "sql", "databricks")).status == "ok"

    def sequences():
        return session._con.execute("SELECT count(*) FROM duckdb_sequences() WHERE starts_with(sequence_name, '__kf_')"
                                    ).fetchall()[0][0]
    try:
        run("CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, n BIGINT GENERATED BY DEFAULT AS IDENTITY, "
            "s STRING)")
        assert sequences() == 2
        run("CREATE OR REPLACE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY, s STRING); INSERT INTO ids (s) "
            "VALUES ('a')")
        assert sequences() == 1
        run("DROP TABLE ids")
        assert sequences() == 0
        run("CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY); DROP TABLE t; DROP TABLE IF EXISTS gone")
        assert sequences() == 0
    finally:
        session.close()


@pytest.mark.parametrize("name", ["__kf_always_z; DROP TABLE victim; SELECT 1 AS done", "__kf_always_z CASCADE",
                                  "__kf_always_" + "a" * 32 + "; DROP TABLE victim"])
def test_a_sequence_drop_only_names_a_sequence_this_module_made(name):
    session = local_sql.DuckDBSession(SessionConfig("nb"))
    try:
        # DuckDB keeps the default's text as written, so a crafted name reaches the stored CREATE TABLE
        session._con.execute(f'CREATE SEQUENCE "{name}"; CREATE TABLE victim (a INT); '
                             f"CREATE TABLE u (id BIGINT DEFAULT nextval('{name}'))")
        written = session._sql("DROP TABLE u", "databricks")
        assert "victim" not in written and "CASCADE" not in written.upper()
        assert session.execute(CellRequest("DROP TABLE u", "sql", "databricks")).status == "ok"
        assert session._con.execute("SELECT count(*) FROM duckdb_tables() WHERE table_name = 'victim'").fetchall() \
            == [(1,)]
    finally:
        session.close()


def test_a_table_dropped_from_another_schema_drops_its_sequence_too():
    session = local_sql.DuckDBSession(SessionConfig("nb"))

    def run(code):
        assert session.execute(CellRequest(code, "sql", "databricks")).status == "ok"
    try:
        run("CREATE SCHEMA o2")
        run("USE o2")
        run("CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY, n STRING)")
        run("USE main")
        run("DROP TABLE o2.t")
        assert session._con.execute("SELECT count(*) FROM duckdb_sequences() WHERE starts_with(sequence_name, '__kf_')"
                                    ).fetchall() == [(0,)]
    finally:
        session.close()


def test_create_table_if_not_exists_keeps_the_table_that_is_there(cell):
    cell("CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY, v INT)")
    _refused(cell("CREATE TABLE IF NOT EXISTS t (id BIGINT, v INT); INSERT INTO t (id, v) VALUES (99, 1)"),
             "A write that gives id a value")
    assert cell("CREATE TABLE IF NOT EXISTS t (id BIGINT GENERATED ALWAYS AS IDENTITY, v INT); "
                "INSERT INTO t (v) VALUES (1); SELECT id, v FROM t") == [[1, 1]]
    assert cell("SELECT count(*) FROM duckdb_sequences() WHERE starts_with(sequence_name, '__kf_')") == [[1]]
