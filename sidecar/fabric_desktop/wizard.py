"""The new notebook wizard: plain cells written from a template and the answers to a few questions.

Nothing here is generated by AI. Each template is a fixed set of cells; the answers (tables,
columns, file paths) are put into the code as Python string literals with ``repr``, so any name
is safe to use. Every notebook the wizard makes reads and writes through ``fabric_desktop.lakehouse``,
so it runs on this PC and as a Fabric Python notebook, and a proof can contain it.

The wizard also saves a **proof contract** in the notebook's metadata (``fabric_desktop.proof``):
the columns that identify a row of each output table and the columns to leave out when the two
runs are compared. The Prove panel starts from it.
"""

