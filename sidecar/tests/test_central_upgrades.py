"""A central platform database made by any earlier release, or a repair that stopped partway, reaches
today's shape with every row kept when Finish or repair (core.ensure_schema) runs again (#1034).

fixtures/central_shapes.json holds every distinct shape ensure_schema made on main, oldest first
(regenerated by fixtures/central_shapes.py). Each test builds that shape in SQLite with one row in
every table, runs today's ensure_schema, and compares with a database today's ensure_schema made
from nothing. SQLite only: the T-SQL spelling of the same statements (UDF_Platform's SQL database) isn't
run here. No tenant calls."""

import json
import re
import sqlite3
from contextlib import closing
from pathlib import Path

import pytest

from fabric_desktop.central import core, policy  # noqa: F401  (policy adds its tables to ensure_schema)

SHAPES = json.loads((Path(__file__).parent / "fixtures" / "central_shapes.json").read_text())
# Values a migration fills in when they are missing or not valid yet (ensure_source_ids numbers sources),
# given here as a real platform has them, so a kept row is compared as it is.
REAL = {("catalog__source", "source_id"): "3", ("catalog__source", "active"): "1"}
DDL = re.compile(r"\s*(CREATE|ALTER|DROP|IF )", re.I)


def _shape(conn):
    names = [n for (n,) in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table' "
                                        "AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    return {n: sorted(c[1] for c in conn.execute(f"PRAGMA table_info('{n}')")) for n in names}


def _today():
    with closing(sqlite3.connect(":memory:")) as conn:  # at import: left open, 3.13 warns wherever gc runs
        core.ensure_schema(core.Db(conn, "sqlite"))
        typed = {n: sorted((c[1], c[2]) for c in conn.execute(f"PRAGMA table_info('{n}')")) for n in _shape(conn)}
        return _shape(conn), typed


TODAY, TODAY_TYPED = _today()


def _connect(path):
    """A file database without a journal file or a flush per commit. The repair test opens one fresh
    database per schema statement, each committed many times; on Windows every commit's journal file
    and flush cost enough (with the virus scanner looking at each new file) that one parameter took
    30 to 40 s and, on a busy runner, passed the 300 s test limit. A transaction that isn't committed
    is still rolled back when the connection closes, which is what the test relies on."""
    conn = sqlite3.connect(path)
    conn.execute("PRAGMA journal_mode = MEMORY")
    conn.execute("PRAGMA synchronous = OFF")
    return conn


def _build(path, shape):
    """The shape, with one row in each table whose every value names its table and column."""
    conn = _connect(path)
    rows = {}
    for i in shape["tables"]:
        name, cols = SHAPES["tables"][i]
        conn.execute(f"CREATE TABLE {name} ({', '.join(f'{c[0]} {c[1]}' + (' PRIMARY KEY' if c[2:] else '') for c in cols)})")
        row = {c[0]: REAL.get((name, c[0]), 7 if c[1] == "INTEGER" else f"{name}.{c[0]}") for c in cols}
        if name == "config__setting":
            row = {"name": "schema_version", "value": "1"}
        conn.execute(f"INSERT INTO {name} ({', '.join(row)}) VALUES ({', '.join('?' * len(row))})", tuple(row.values()))
        rows[name] = row
    conn.commit()
    conn.close()
    return rows


def _check(path, rows):
    conn = _connect(path)
    try:
        got = _shape(conn)
        missing = {t: sorted(set(cols) - set(got.get(t, []))) for t, cols in TODAY.items()
                   if set(cols) - set(got.get(t, []))}
        assert missing == {}
        for table, row in rows.items():
            if table == "config__setting":
                continue
            where = " AND ".join(f"{c} = ?" for c in row)
            [(n,)] = conn.execute(f"SELECT COUNT(*) FROM {table} WHERE {where}", tuple(row.values())).fetchall()
            assert n == 1, f"{table} lost or changed its row"
        assert conn.execute("SELECT value FROM config__setting WHERE name = 'schema_version'").fetchall() == [
            (str(core.SCHEMA_VERSION),)]
    finally:
        conn.close()


def _repair(path):
    conn = _connect(path)
    try:
        return core.ensure_schema(core.Db(conn, "sqlite"))
    finally:
        conn.close()


class Stopped(Exception):
    pass


def _repair_stopping_at(path, n, monkeypatch):
    """Finish or repair, with its nth schema statement failing (a timeout, a dropped connection)."""
    run, seen = core.Db.run, []

    def failing(self, sql, *args, **kwargs):
        if DDL.match(sql):
            seen.append(sql)
            if len(seen) == n:
                raise Stopped(sql)
        return run(self, sql, *args, **kwargs)

    with monkeypatch.context() as m:
        m.setattr(core.Db, "run", failing)
        try:
            _repair(path)
        except Stopped:
            return True
    return False


IDS = [f"{s['date']}-{s['commit']}" for s in SHAPES["shapes"]]


def test_the_fixture_s_newest_shape_is_today_s():
    newest = SHAPES["shapes"][-1]
    assert {SHAPES["tables"][i][0]: sorted((c[0], c[1]) for c in SHAPES["tables"][i][1])
            for i in newest["tables"]} == TODAY_TYPED, \
        "regenerate fixtures/central_shapes.json with fixtures/central_shapes.py"


@pytest.mark.parametrize("shape", SHAPES["shapes"], ids=IDS)
def test_a_database_from_an_earlier_release_upgrades_with_every_row_kept(tmp_path, shape):
    path = tmp_path / "platform.sqlite"
    rows = _build(path, shape)
    _repair(path)
    _check(path, rows)
    assert _repair(path)["created"] == []  # and a second repair has nothing left to do


@pytest.mark.parametrize("shape", [None, *SHAPES["shapes"]], ids=["new", *IDS])
def test_a_repair_stopped_at_any_statement_finishes_when_run_again(tmp_path, monkeypatch, shape):
    stops, done = 0, False
    for n in range(1, 500):
        path = tmp_path / f"platform-{n}.sqlite"
        rows = _build(path, shape) if shape else {}
        if not _repair_stopping_at(path, n, monkeypatch):
            done = True
            break
        stops += 1
        _repair(path)
        _check(path, rows)
    assert done, "a repair has 500 or more schema statements: raise the limit"
    assert shape is SHAPES["shapes"][-1] or stops > 0  # every older shape has statements to stop at
