"""The new notebook wizard: plain cells written from a template and the answers to a few questions.

Nothing here is generated by AI. Each template is a fixed set of cells; the answers (tables,
columns, file paths) are put into the code as Python string literals with ``repr``, so any name
is safe to use. Every notebook the wizard makes reads and writes through ``fabric_desktop.lakehouse``,
so it runs on this PC and as a Fabric Python notebook, and a proof can contain it.

The wizard also saves a **proof contract** in the notebook's metadata (``fabric_desktop.proof``):
the columns that identify a row of each output table and the columns to leave out when the two
runs are compared. The Prove panel starts from it.
"""

from __future__ import annotations

import re
from typing import Any

from . import verify

_TABLE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)?$")
_FILE = re.compile(r"^Files/[^\\\x00]+\.(csv|parquet|json)$", re.IGNORECASE)

TEMPLATES: list[dict[str, Any]] = [
    {"id": "clean", "title": "Clean a table",
     "text": "Read one table, keep and rename columns, drop rows with no key and duplicates, write a new table.",
     "fields": ["source", "columns", "keys", "output", "mode"]},
    {"id": "join_aggregate", "title": "Join and aggregate",
     "text": "Read a table, join another on a column, group by columns, write the result.",
     "fields": ["source", "join_table", "join_on", "group_by", "output", "mode"]},
    {"id": "load_file", "title": "Load a file into a table",
     "text": "Read a CSV, Parquet or JSON file under Files/, check its key columns and write it as a Delta table.",
     "fields": ["file", "keys", "output", "mode"]},
]

FIELDS = {
    "source": "Table to read (schema.table)",
    "join_table": "Table to join (schema.table)",
    "join_on": "Column to join on",
    "group_by": "Columns to group by",
    "columns": "Columns to keep (all when empty)",
    "file": "File under Files/",
    "keys": "Columns that identify a row",
    "output": "Table to write (schema.table)",
    "mode": "Write mode",
}


def templates() -> dict[str, Any]:
    return {"templates": TEMPLATES, "fields": FIELDS, "modes": ["overwrite", "append"]}


def _names(value: Any) -> list[str]:
    if isinstance(value, str):
        value = value.split(",")
    return [str(v).strip() for v in value or [] if str(v).strip()]


def _table(value: Any, label: str) -> str:
    text = str(value or "").strip()
    if not _TABLE.match(text):
        raise ValueError(f"{label} must be a table name like dbo.orders.")
    return text


def _check_cell(df: str, keys: list[str]) -> str:
    return (f"# Check: every row has its key, and each key appears once\n"
            f"keys = {keys!r}\n"
            f"missing = {df}.filter(pl.any_horizontal([pl.col(k).is_null() for k in keys])).height\n"
            f"duplicates = {df}.height - {df}.unique(subset=keys).height\n"
            f"assert missing == 0, f\"{{missing}} rows have no value in {{keys}}\"\n"
            f"assert duplicates == 0, f\"{{duplicates}} rows repeat a key in {{keys}}\"\n"
            f"print(f\"{{{df}.height:,}} rows, keys unique\")")


def build(template: str, values: dict[str, Any]) -> dict[str, Any]:
    """The cells and proof contract for one template and its answers. Raises ValueError with a
    sentence the wizard shows when an answer is missing or malformed."""
    t = next((x for x in TEMPLATES if x["id"] == template), None)
    if t is None:
        raise ValueError(f"No template {template!r}.")
    v = values or {}
    output = _table(v.get("output"), "The table to write")
    mode = v.get("mode") or "overwrite"
    if mode not in ("overwrite", "append"):
        raise ValueError("The write mode is overwrite or append.")
    keys = _names(v.get("keys"))
    ignore = _names(v.get("ignore"))
    head = "import polars as pl\nfrom fabric_desktop import lakehouse"
    cells: list[dict[str, Any]] = []

    def md(text: str) -> None:
        cells.append({"type": "markdown", "source": text})

    def code(text: str) -> None:
        cells.append({"type": "code", "source": text})

    if template == "clean":
        source = _table(v.get("source"), "The table to read")
        columns = _names(v.get("columns"))
        if not keys:
            raise ValueError("Name the columns that identify a row, so duplicates can be dropped and the proof can match rows.")
        md(f"# Clean {source}\n\nReads `{source}`, keeps the columns it needs, drops rows with no key and "
           f"duplicate keys, and writes `{output}`. Made by the new notebook wizard.")
        code(head)
        code(f"df = lakehouse.read_table({source!r})\ndf.head()")
        keep = f"df = df.select({columns!r})\n" if columns else "# Keep every column. To keep some: df = df.select([...])\n"
        code(keep + f"df = df.drop_nulls(subset={keys!r}).unique(subset={keys!r}, keep=\"first\", maintain_order=True)\ndf.head()")
        code(_check_cell("df", keys))
        code(f"lakehouse.write_table(df, {output!r}, mode={mode!r})")
    elif template == "join_aggregate":
        source = _table(v.get("source"), "The table to read")
        other = _table(v.get("join_table"), "The table to join")
        on = _names(v.get("join_on"))
        group = _names(v.get("group_by"))
        if len(on) != 1:
            raise ValueError("Name one column to join on.")
        if not group:
            raise ValueError("Name the columns to group by.")
        keys = keys or group
        md(f"# {output} from {source} and {other}\n\nJoins `{source}` with `{other}` on `{on[0]}`, groups by "
           f"{', '.join(f'`{g}`' for g in group)} and writes `{output}`. Made by the new notebook wizard.")
        code(head)
        code(f"left = lakehouse.read_table({source!r})\nright = lakehouse.read_table({other!r})\nleft.head()")
        code(f"joined = left.join(right, on={on[0]!r}, how=\"inner\")\njoined.head()")
        code(f"# Add the measures you need, for example pl.col(\"amount\").sum().alias(\"amount\")\n"
             f"out = joined.group_by({group!r}).agg(pl.len().alias(\"rows\")).sort({group!r})\nout.head()")
        code(_check_cell("out", keys))
        code(f"lakehouse.write_table(out, {output!r}, mode={mode!r})")
    else:  # load_file
        path = str(v.get("file") or "").strip()
        if not _FILE.match(path) or ".." in path.split("/"):
            raise ValueError("The file must be a .csv, .parquet or .json file under Files/, like Files/raw/orders.csv.")
        if not keys:
            raise ValueError("Name the columns that identify a row, so the load can be checked and proven.")
        reader = {"csv": "read_csv", "parquet": "read_parquet", "json": "read_json"}[path.rsplit(".", 1)[1].lower()]
        md(f"# Load {path}\n\nReads `{path}` from the lakehouse, checks its key columns and writes `{output}`. "
           "Made by the new notebook wizard.")
        code(head)
        code(f"df = lakehouse.{reader}({path!r})\ndf.head()")
        code(_check_cell("df", keys))
        code(f"lakehouse.write_table(df, {output!r}, mode={mode!r})")

    rules = {"keys": keys, "ignore": ignore}
    verify.rules(rules)
    return {"cells": cells, "proof": {"tables": {output: rules}}, "template": template}
